export function controlCase(
  chosen: (typeof CHOSEN)[number],
  snapshot: Snapshot,
  controls: WrittenClaim[],
  judgements: Judgement[],
): DigResult {
  const evidence = snapshot.cases.find((c) => c.id === chosen.id)?.evidence;
  const control = controls.find((c) => c.id === chosen.id && c.text === chosen.text);
  const judgement = judgements.find(
    (j) => j.kind && j.id === chosen.id && j.claim === chosen.text && j.replay === chosen.replay,
  );
  if (!evidence || !control || !judgement)
    throw new Error(`no kept evidence, control or judgement for ${chosen.id}`);
  const { entailment } = controlNarrative(control, judgement, evidence);
  const narrative: Narrative = {
    answer: control.text,
    answerable: true,
    recorded: true,
    citations: control.citations,
    claims: [{ text: control.text, citations: control.citations }],
  };
  return { evidence, narrative: verify(evidence, narrative, entailment) };
}

export function controlCases(): { note: string; cases: Record<string, DigResult> } {
  const snapshot = JSON.parse(readFileSync(EVIDENCE, "utf8")) as Snapshot;
  const controls = parseControls(readFileSync(CONTROLS, "utf8"));
  const judgements = parseReplay(readFileSync(REPLAY, "utf8")).judgements;
  return {
    note: NOTE,
    cases: Object.fromEntries(
      CHOSEN.map((chosen) => [chosen.id, controlCase(chosen, snapshot, controls, judgements)]),
    ),
  };
}

function main() {
  const out = process.argv[2];
  if (!out) {
    console.error("usage: npx tsx scripts/control-cases.ts <out.json>");
    process.exit(1);
  }
  writeFileSync(out, `${JSON.stringify(controlCases(), null, 2)}\n`);
}

if (process.argv[1]?.endsWith("control-cases.ts")) main();
